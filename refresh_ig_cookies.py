#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Автоматичне оновлення Instagram сесії і кукі на VPS.

Що робить:
    1. Перевіряє, чи поточні cookies_instagram.txt ще валідні (sessionid живий).
       Якщо так — нічого не робить (щоб не логінитись з datacenter IP без потреби).
    2. Інакше логінить акаунт через instagrapi (IG_USERNAME / IG_PASSWORD),
       зберігає ig_session.json і перегенеровує cookies_instagram.txt (Netscape).
    3. Новий cookies-файл замінює старий тільки після успішної перевірки.

Credentials читаються з /var/opt/mieshania/ig.env (chmod 600), далі з .env.
Опційно IG_TOTP_SECRET — seed 2FA (authenticator app).

Використання:
    refresh_ig_cookies.py            # оновити, якщо кукі протухли
    refresh_ig_cookies.py --force    # логін в будь-якому разі
    refresh_ig_cookies.py --check    # тільки перевірка (exit 0 = валідні)
"""

import argparse
import datetime
import json
import os
import pathlib
import shutil
import sys
import time

import requests

BASE_DIR = pathlib.Path(os.getenv("MIESHANIA_DIR", "/var/opt/mieshania"))
CREDS_FILES = [BASE_DIR / "ig.env", BASE_DIR / ".env"]
SESSION_FILE = pathlib.Path(os.getenv("IG_SESSION_FILE", str(BASE_DIR / "ig_session.json")))
COOKIES_FILE = pathlib.Path(os.getenv("COOKIES_INSTAGRAM_PATH", str(BASE_DIR / "cookies_instagram.txt")))
if not COOKIES_FILE.is_absolute():
    COOKIES_FILE = BASE_DIR / COOKIES_FILE
LOG_FILE = "/var/log/mieshania.downloader.log"

UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/124.0 Safari/537.36")
CHECK_URL = "https://www.instagram.com/api/v1/accounts/current_user/?edit=true"
IG_APP_ID = "936619743392459"


def log(msg: str) -> None:
    line = f"{datetime.datetime.now():%Y-%m-%d %H:%M:%S} [IG-REFRESH] {msg}"
    print(line)
    try:
        with open(LOG_FILE, "a", encoding="utf-8") as f:
            f.write(line + "\n")
    except Exception:
        pass


def load_env() -> None:
    """Підвантажує змінні з ig.env/.env, не перетираючи вже виставлені в оточенні."""
    for path in CREDS_FILES:
        if not path.exists():
            continue
        for raw in path.read_text(encoding="utf-8").splitlines():
            raw = raw.strip()
            if not raw or raw.startswith("#") or "=" not in raw:
                continue
            k, v = raw.split("=", 1)
            v = v.strip().strip('"').strip("'")
            os.environ.setdefault(k.strip(), v)


def read_cookies(path: pathlib.Path) -> dict:
    """Netscape cookies.txt -> {name: value} (тільки instagram.com)."""
    out = {}
    if not path.exists():
        return out
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if line.startswith("#HttpOnly_"):
            line = line[len("#HttpOnly_"):]
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) >= 7 and "instagram.com" in parts[0]:
            out[parts[5]] = parts[6]
    return out


def cookies_valid(cookies: dict) -> bool:
    """sessionid живий, якщо Instagram віддає current_user (а не 401/redirect на логін)."""
    if not cookies.get("sessionid"):
        return False
    try:
        r = requests.get(
            CHECK_URL,
            cookies=cookies,
            headers={
                "User-Agent": UA,
                "X-IG-App-ID": IG_APP_ID,
                "X-CSRFToken": cookies.get("csrftoken", ""),
                "Referer": "https://www.instagram.com/",
            },
            allow_redirects=False,
            timeout=20,
        )
        return r.status_code == 200 and '"user"' in r.text
    except Exception as e:
        log(f"validation request failed: {e}")
        return False


def write_netscape(path: pathlib.Path, cookies: dict) -> None:
    far = int(time.time()) + 365 * 24 * 3600
    lines = ["# Netscape HTTP Cookie File", "# Generated by refresh_ig_cookies.py", ""]
    for name, value in cookies.items():
        lines.append(f".instagram.com\tTRUE\t/\tTRUE\t{far}\t{name}\t{value}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(path, 0o600)


def login_with_instagrapi() -> tuple:
    from instagrapi import Client

    username = os.getenv("IG_USERNAME", "")
    password = os.getenv("IG_PASSWORD", "")
    if not username or not password:
        raise RuntimeError("IG_USERNAME / IG_PASSWORD не задані (ig.env)")

    cl = Client()
    cl.delay_range = [1, 3]

    code = ""
    seed = os.getenv("IG_TOTP_SECRET", "").strip()
    if seed:
        code = cl.totp_generate_code(seed)

    # Повторний логін поверх старої сесії зберігає device settings (менше підозр у IG)
    if SESSION_FILE.exists():
        try:
            cl.set_settings(json.loads(SESSION_FILE.read_text(encoding="utf-8")))
        except Exception as e:
            log(f"old session not reusable: {e}")

    log(f"logging in as {username}")
    cl.login(username, password, verification_code=code)
    return cl, username


def build_cookies(cl, old: dict) -> dict:
    """Збирає cookies для yt-dlp із instagrapi-клієнта, зберігаючи інші старі (datr, ig_did…)."""
    new = {k: v for k, v in old.items() if k not in ("sessionid", "ds_user_id")}
    jar = {}
    try:
        jar = {c.name: c.value for c in cl.private.cookies}
    except Exception:
        pass
    sessionid = cl.sessionid or jar.get("sessionid")
    if not sessionid:
        raise RuntimeError("instagrapi не повернув sessionid")
    new["sessionid"] = sessionid
    new["ds_user_id"] = str(cl.user_id or jar.get("ds_user_id") or "")
    csrf = jar.get("csrftoken") or getattr(cl, "token", None)
    if csrf:
        new["csrftoken"] = csrf
    mid = jar.get("mid") or getattr(cl, "mid", None)
    if mid:
        new["mid"] = mid
    return {k: v for k, v in new.items() if v}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="логін навіть якщо кукі валідні")
    ap.add_argument("--check", action="store_true", help="тільки перевірити кукі")
    args = ap.parse_args()

    load_env()
    old = read_cookies(COOKIES_FILE)
    valid = cookies_valid(old)

    if args.check:
        log("cookies valid" if valid else "cookies INVALID")
        return 0 if valid else 1
    if valid and not args.force:
        log("cookies still valid — nothing to do")
        return 0

    log("cookies invalid/missing — refreshing" if not valid else "forced refresh")
    try:
        cl, _ = login_with_instagrapi()
        new = build_cookies(cl, old)
    except Exception as e:
        log(f"LOGIN FAIL: {type(e).__name__}: {e}")
        log("Якщо challenge/2FA — залогінься з residential IP: refresh_ig_session.py")
        return 2

    if not cookies_valid(new):
        log("new cookies failed validation — старі файли НЕ перезаписано")
        return 3

    # Зберігаємо сесію instagrapi і кукі (з бекапом)
    SESSION_FILE.write_text(json.dumps(cl.get_settings()), encoding="utf-8")
    os.chmod(SESSION_FILE, 0o600)
    if COOKIES_FILE.exists():
        shutil.copy2(COOKIES_FILE, str(COOKIES_FILE) + ".bak")
    tmp = COOKIES_FILE.with_suffix(".tmp")
    write_netscape(tmp, new)
    os.replace(tmp, COOKIES_FILE)
    log(f"OK: {COOKIES_FILE.name} + {SESSION_FILE.name} оновлено")
    return 0


if __name__ == "__main__":
    sys.exit(main())
